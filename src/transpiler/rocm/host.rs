// Rust host-side code emitter for the ROCm/HIP backend.
//
// This is structurally a close relative of `cuda::host` — the Boring-AST-to-
// Rust statement/expression codegen (`emit_fn`/`emit_stmt`/`expr`/pattern
// matching/dict handling/GPU-residency tracking) is entirely target-agnostic
// and carried over verbatim. What's different is the GPU API surface itself:
// there is no mature safe Rust crate for ROCm/HIP analogous to `cudarc`, so
// `ROCM_HOST_PRELUDE` below hand-rolls a small `extern "C"` FFI layer (linking
// `libamdhip64`, ROCm's stable documented C API) plus a safe wrapper
// (`HipContext`/`HipStream`/`HipModule`/`DeviceBuffer<T>`/`LaunchBuilder`)
// deliberately shaped like cudarc's own API (same method names: `alloc_zeros`,
// `clone_htod`, `clone_dtoh`, `load_function`, `launch_builder`/`.arg`/
// `.launch`, `new_stream_with_priority`, ...) — see `rocm::mod`'s doc comment
// for the full rationale. That's what keeps the rest of this file's diff
// against `cuda::host` down to mechanical type-name substitutions
// (`CudaContext`→`HipContext`, `CudaSlice<T>`→`DeviceBuffer<T>`, etc.) instead
// of re-deriving the whole AST→Rust pipeline from scratch.

