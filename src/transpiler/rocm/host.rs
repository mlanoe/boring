#[derive(Debug)]
struct HipError { code: i32, message: String }

impl HipError {
    fn from_code(code: __boring_hip_ffi::hipError_t) -> Self {
        let message = unsafe {
            let ptr = __boring_hip_ffi::hipGetErrorString(code);
            if ptr.is_null() { "unknown HIP error".to_string() }
            else { CStr::from_ptr(ptr).to_string_lossy().into_owned() }
        };
        HipError { code: code as i32, message }
    }
}
impl HipError {
    // Short category prefix classified from the raw HIP error code, on top
    // of `hipGetErrorString`'s own message (already fetched into `message`
    // above) -- for the handful of failure classes a caller most often cares
    // about at a glance (out of memory, illegal access, timeout, ...).
    // These numeric codes mirror CUDA's `CUresult` values (HIP is designed
    // as a near-1:1 source-level match for the CUDA driver API -- see
    // `rocm-backend.md`'s own rationale for the rest of this backend), but
    // that mirroring is NOT independently verified against a real ROCm
    // install here (none available in this project's dev environment) --
    // same caveat this backend's docs already carry elsewhere.
    fn category(&self) -> &'static str {
        match self.code {
            // Mirrors CUDA's CUDA_ERROR_INVALID_VALUE (see the identical
            // constant in cuda::host) -- the real rejection an oversized
            // `block =` hits at `hipModuleLaunchKernel`. Boring deliberately
            // does not duplicate this check at compile time or in the
            // interpreter; it defers entirely to this real runtime rejection.
            1   => "GPU launch configuration invalid (e.g. block size exceeds device limits)",
            2   => "GPU out of memory",
            700 => "GPU illegal memory access",
            701 => "GPU launch out of resources",
            702 => "GPU operation timed out",
            714 => "GPU stack overflow",
            214 | 709 => "GPU device lost",
            _ => "GPU kernel launch failed",
        }
    }
}
impl std::fmt::Display for HipError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}: HIP error {}: {}", self.category(), self.code, self.message)
    }
}
impl std::error::Error for HipError {}

fn __boring_hip_check(code: __boring_hip_ffi::hipError_t) -> Result<(), HipError> {
    if code == 0 { Ok(()) } else { Err(HipError::from_code(code)) }
}

// ── HipContext -- one GPU device. HIP's runtime API has no explicit context
// ── object the way the CUDA driver API does; `hipSetDevice` before every
// ── operation models the same "which device is this for" semantics explicitly
// ── instead of relying on a thread-implicit current device.
struct HipContext { ordinal: i32 }
unsafe impl Send for HipContext {}
unsafe impl Sync for HipContext {}

impl HipContext {
    fn new(ordinal: usize) -> Result<Arc<HipContext>, HipError> {
        unsafe { __boring_hip_check(__boring_hip_ffi::hipSetDevice(ordinal as c_int))?; }
        Ok(Arc::new(HipContext { ordinal: ordinal as i32 }))
    }

    fn device_count() -> Result<i32, HipError> {
        let mut n: c_int = 0;
        unsafe { __boring_hip_check(__boring_hip_ffi::hipGetDeviceCount(&mut n))?; }
        Ok(n)
    }

    fn make_current(&self) -> Result<(), HipError> {
        unsafe { __boring_hip_check(__boring_hip_ffi::hipSetDevice(self.ordinal)) }
    }

    fn default_stream(self: &Arc<Self>) -> Arc<HipStream> {
        self.new_stream().expect("hip: failed to create default stream")
    }

    fn new_stream(self: &Arc<Self>) -> Result<Arc<HipStream>, HipError> {
        self.new_stream_with_priority(0)
    }

    fn new_stream_with_priority(self: &Arc<Self>, priority: i32) -> Result<Arc<HipStream>, HipError> {
        self.make_current()?;
        let mut raw: __boring_hip_ffi::hipStream_t = std::ptr::null_mut();
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipStreamCreateWithPriority(&mut raw, 0, priority))?;
        }
        Ok(Arc::new(HipStream { raw, _ctx: Arc::clone(self) }))
    }

    fn load_module(self: &Arc<Self>, image: &[u8]) -> Result<Arc<HipModule>, HipError> {
        self.make_current()?;
        let mut raw: __boring_hip_ffi::hipModule_t = std::ptr::null_mut();
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipModuleLoadData(&mut raw, image.as_ptr() as *const c_void))?;
        }
        Ok(Arc::new(HipModule { raw, _ctx: Arc::clone(self) }))
    }

    fn ordinal(&self) -> usize { self.ordinal as usize }

    fn name(&self) -> Result<String, HipError> {
        self.make_current()?;
        let mut buf = [0u8; 256];
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipDeviceGetName(buf.as_mut_ptr() as *mut c_char, buf.len() as c_int, self.ordinal))?;
            Ok(CStr::from_ptr(buf.as_ptr() as *const c_char).to_string_lossy().into_owned())
        }
    }

    fn total_mem(&self) -> Result<usize, HipError> {
        self.make_current()?;
        let mut bytes: usize = 0;
        unsafe { __boring_hip_check(__boring_hip_ffi::hipDeviceTotalMem(&mut bytes, self.ordinal))?; }
        Ok(bytes)
    }

    fn mem_get_info(&self) -> Result<(usize, usize), HipError> {
        self.make_current()?;
        let (mut free, mut total) = (0usize, 0usize);
        unsafe { __boring_hip_check(__boring_hip_ffi::hipMemGetInfo(&mut free, &mut total))?; }
        Ok((free, total))
    }

    fn compute_capability(&self) -> Result<(i32, i32), HipError> {
        self.make_current()?;
        let (mut major, mut minor): (c_int, c_int) = (0, 0);
        unsafe { __boring_hip_check(__boring_hip_ffi::hipDeviceComputeCapability(&mut major, &mut minor, self.ordinal))?; }
        Ok((major as i32, minor as i32))
    }

    // `hipDeviceAttribute_t`'s numeric values are NOT guaranteed ABI-stable
    // across ROCm releases (unlike the dedicated queries above, which are
    // real, stable HIP API entry points on their own) -- rather than hardcode
    // an attribute ID that could silently mean something else on a different
    // ROCm version, the three IDs below are read at *build time* from
    // whatever ROCm headers are actually installed on this machine (see
    // build.rs's `probe_hip_device_attributes`, generating
    // `OUT_DIR/boring_hip_attrs.rs`). If that probe couldn't run, the
    // constants fall back to -1 and `get_attribute` reports a clear error
    // instead of querying with a nonsense attribute ID.
    fn warp_size(&self) -> Result<i32, HipError> {
        self.get_attribute(BORING_HIP_ATTR_WARP_SIZE, "warp_size")
    }
    fn max_threads(&self) -> Result<i32, HipError> {
        self.get_attribute(BORING_HIP_ATTR_MAX_THREADS_PER_BLOCK, "max_threads")
    }
    fn max_shared_mem(&self) -> Result<i32, HipError> {
        self.get_attribute(BORING_HIP_ATTR_SHARED_MEM_PER_BLOCK, "max_shared_mem")
    }

    fn get_attribute(&self, attr: i32, name: &str) -> Result<i32, HipError> {
        if attr < 0 {
            return Err(HipError { code: -1, message: format!(
                "{name}() is not supported: this project was built without a usable ROCm/HIP \
                 toolchain header (hip/hip_runtime_api.h) to probe -- rebuild with a valid ROCm \
                 install, or query via rocminfo"
            ) });
        }
        self.make_current()?;
        let mut val: c_int = 0;
        unsafe { __boring_hip_check(__boring_hip_ffi::hipDeviceGetAttribute(&mut val, attr, self.ordinal))?; }
        Ok(val as i32)
    }
}

struct HipStream { raw: __boring_hip_ffi::hipStream_t, _ctx: Arc<HipContext> }
unsafe impl Send for HipStream {}
unsafe impl Sync for HipStream {}

impl HipStream {
    fn synchronize(&self) -> Result<(), HipError> {
        unsafe { __boring_hip_check(__boring_hip_ffi::hipStreamSynchronize(self.raw)) }
    }

    /// GPU-side ordering: makes every future op on `self` wait for everything
    /// already enqueued on `other`, without a CPU-blocking sync.
    fn join(&self, other: &Arc<HipStream>) -> Result<(), HipError> {
        unsafe {
            let mut event: __boring_hip_ffi::hipEvent_t = std::ptr::null_mut();
            __boring_hip_check(__boring_hip_ffi::hipEventCreate(&mut event))?;
            __boring_hip_check(__boring_hip_ffi::hipEventRecord(event, other.raw))?;
            __boring_hip_check(__boring_hip_ffi::hipStreamWaitEvent(self.raw, event, 0))?;
            __boring_hip_check(__boring_hip_ffi::hipEventDestroy(event))?;
        }
        Ok(())
    }

    fn alloc_zeros<T>(self: &Arc<Self>, len: usize) -> Result<DeviceBuffer<T>, HipError> {
        let byte_len = len * std::mem::size_of::<T>();
        let mut ptr: *mut c_void = std::ptr::null_mut();
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipMalloc(&mut ptr, byte_len.max(1)))?;
            __boring_hip_check(__boring_hip_ffi::hipMemsetD8Async(ptr, 0, byte_len, self.raw))?;
        }
        Ok(DeviceBuffer { ptr, len, stream: Arc::clone(self), _marker: PhantomData })
    }

    fn clone_htod<T: Copy>(self: &Arc<Self>, src: &[T]) -> Result<DeviceBuffer<T>, HipError> {
        let byte_len = src.len() * std::mem::size_of::<T>();
        let mut ptr: *mut c_void = std::ptr::null_mut();
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipMalloc(&mut ptr, byte_len.max(1)))?;
            __boring_hip_check(__boring_hip_ffi::hipMemcpyHtoDAsync(ptr, src.as_ptr() as *const c_void, byte_len, self.raw))?;
        }
        Ok(DeviceBuffer { ptr, len: src.len(), stream: Arc::clone(self), _marker: PhantomData })
    }

    fn clone_dtoh<T: Copy + Default>(&self, buf: &DeviceBuffer<T>) -> Result<Vec<T>, HipError> {
        let mut out = vec![T::default(); buf.len];
        let byte_len = buf.len * std::mem::size_of::<T>();
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipMemcpyDtoHAsync(out.as_mut_ptr() as *mut c_void, buf.ptr, byte_len, self.raw))?;
        }
        Ok(out)
    }

    fn launch_builder<'a>(&'a self, func: &'a HipFunction) -> LaunchBuilder<'a> {
        LaunchBuilder { func, stream: self, ptrs: Vec::new() }
    }
}

struct HipModule { raw: __boring_hip_ffi::hipModule_t, _ctx: Arc<HipContext> }
unsafe impl Send for HipModule {}
unsafe impl Sync for HipModule {}

impl HipModule {
    fn load_function(&self, name: &str) -> Result<HipFunction, HipError> {
        let cname = CString::new(name).expect("kernel name contains a NUL byte");
        let mut raw: __boring_hip_ffi::hipFunction_t = std::ptr::null_mut();
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipModuleGetFunction(&mut raw, self.raw, cname.as_ptr()))?;
        }
        Ok(HipFunction { raw })
    }

    /// Upload `data` to a `__constant__`-declared global symbol named `name` in
    /// this module -- one call replacing cudarc's get_global/transmute_mut/
    /// memcpy_htod dance, since this backend controls both sides of the FFI.
    fn upload_constant<T: Copy>(&self, stream: &Arc<HipStream>, name: &str, data: &[T]) -> Result<(), HipError> {
        let cname = CString::new(name).expect("global symbol name contains a NUL byte");
        let mut dptr: __boring_hip_ffi::hipDeviceptr_t = std::ptr::null_mut();
        let mut size: usize = 0;
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipModuleGetGlobal(&mut dptr, &mut size, self.raw, cname.as_ptr()))?;
            let byte_len = data.len() * std::mem::size_of::<T>();
            __boring_hip_check(__boring_hip_ffi::hipMemcpyHtoDAsync(dptr, data.as_ptr() as *const c_void, byte_len, stream.raw))?;
        }
        Ok(())
    }
}

#[derive(Clone, Copy)]
struct HipFunction { raw: __boring_hip_ffi::hipFunction_t }
unsafe impl Send for HipFunction {}
unsafe impl Sync for HipFunction {}

struct DeviceBuffer<T> {
    ptr: *mut c_void,
    len: usize,
    stream: Arc<HipStream>,
    _marker: PhantomData<T>,
}
unsafe impl<T> Send for DeviceBuffer<T> {}
unsafe impl<T> Sync for DeviceBuffer<T> {}

impl<T> DeviceBuffer<T> {
    #[allow(dead_code)]
    fn len(&self) -> usize { self.len }
}

impl<T> Drop for DeviceBuffer<T> {
    fn drop(&mut self) {
        if !self.ptr.is_null() {
            unsafe { let _ = __boring_hip_ffi::hipFree(self.ptr); }
        }
    }
}

// Device-to-device copy -- a correctness-preserving fallback for the rare case
// something needs the same resident value twice, not the common path (every
// real call site here moves a DeviceBuffer instead of cloning it).
impl<T> Clone for DeviceBuffer<T> {
    fn clone(&self) -> Self {
        let byte_len = self.len * std::mem::size_of::<T>();
        let mut ptr: *mut c_void = std::ptr::null_mut();
        unsafe {
            let code = __boring_hip_ffi::hipMalloc(&mut ptr, byte_len.max(1));
            assert_eq!(code, 0, "hip: device buffer clone (hipMalloc) failed: {}", HipError::from_code(code));
            let code = __boring_hip_ffi::hipMemcpyDtoDAsync(ptr, self.ptr, byte_len, self.stream.raw);
            assert_eq!(code, 0, "hip: device buffer clone (hipMemcpyDtoD) failed: {}", HipError::from_code(code));
        }
        DeviceBuffer { ptr, len: self.len, stream: Arc::clone(&self.stream), _marker: PhantomData }
    }
}

/// Per-kernel-parameter value that can be pushed onto a `LaunchBuilder` --
/// implemented for `&mut DeviceBuffer<T>` (pushes a pointer to the device
/// pointer itself, matching what a `T*` kernel parameter expects) and for
/// `&scalar` (pushes a pointer to the scalar's own storage). Both are valid
/// only for the duration of the enclosing `hipModuleLaunchKernel` call, which
/// happens synchronously inside `LaunchBuilder::launch` while the borrows are
/// still alive -- see that method's safety doc.
trait BoringKernelArg { fn boring_kernel_ptr(self) -> *mut c_void; }

impl<'a, T> BoringKernelArg for &'a mut DeviceBuffer<T> {
    fn boring_kernel_ptr(self) -> *mut c_void {
        &mut self.ptr as *mut *mut c_void as *mut c_void
    }
}

macro_rules! boring_impl_scalar_kernel_arg {
    ($($t:ty),*) => { $(
        impl<'a> BoringKernelArg for &'a $t {
            fn boring_kernel_ptr(self) -> *mut c_void { self as *const $t as *mut c_void }
        }
    )* };
}
boring_impl_scalar_kernel_arg!(i8, u8, i16, u16, i32, u32, i64, u64, isize, usize, f32, f64, bool);

// `Dimension` (boring's built-in 2-D kernel-size type, see `DIMENSION_STRUCT_RUST`
// below) is a `#[repr(C)] Copy` struct passed by value as a kernel parameter --
// same by-address treatment as the scalar impls above.
impl<'a> BoringKernelArg for &'a Dimension {
    fn boring_kernel_ptr(self) -> *mut c_void { self as *const Dimension as *mut c_void }
}

struct LaunchConfig { block_dim: (u32, u32, u32), grid_dim: (u32, u32, u32), shared_mem_bytes: u32 }

struct LaunchBuilder<'a> { func: &'a HipFunction, stream: &'a HipStream, ptrs: Vec<*mut c_void> }

impl<'a> LaunchBuilder<'a> {
    fn arg<A: BoringKernelArg>(&mut self, a: A) -> &mut Self {
        self.ptrs.push(a.boring_kernel_ptr());
        self
    }

    /// # Safety
    /// Every pointer pushed via `.arg(...)` must stay valid (the borrowed
    /// field it points into must not move/drop) until this call returns --
    /// true for every call site this backend generates, since the launcher is
    /// built and consumed within the same `__boring_launch` call, borrowing
    /// `self`'s own fields directly.
    unsafe fn launch(&mut self, cfg: LaunchConfig) -> Result<(), HipError> {
        unsafe {
            __boring_hip_check(__boring_hip_ffi::hipModuleLaunchKernel(
                self.func.raw,
                cfg.grid_dim.0, cfg.grid_dim.1, cfg.grid_dim.2,
                cfg.block_dim.0, cfg.block_dim.1, cfg.block_dim.2,
                cfg.shared_mem_bytes,
                self.stream.raw,
                self.ptrs.as_mut_ptr(),
                std::ptr::null_mut(),
            ))
        }
    }
}

// Each handle owns the HIP stream its kernel was launched on, so `.wait`
// synchronizes only that stream (not the whole device). `after = [..]`
// dependencies are wired GPU-side via stream ordering (`HipStream::join`), no
// CPU sync.
#[must_use = "a KernelHandle must be waited on (.wait/.inner) or the launch may not be synchronized"]
struct KernelHandle<T> { inner: T, stream: Arc<HipStream> }
impl<T> KernelHandle<T> {
    fn wait(self) -> Result<T, Box<dyn std::error::Error + Send + Sync>> {
        self.stream.synchronize()?;
        Ok(self.inner)
    }
    fn done(&self) -> bool { true }
}
