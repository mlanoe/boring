// Boring -> portable CPU/SIMD backend.  The generated crate deliberately uses
// no GPU API.  Work-items retain the GPU coordinate model; the innermost x
// dimension is emitted as a tight, fixed-width chunk loop so LLVM can use the
// vector register set selected by the generated runtime's feature probe.

use crate::ast::*;

pub struct SimdOutput {
    pub host_rs: String,
    pub cargo_toml: String,
    pub kernel_names: Vec<String>,
    pub errors: Vec<crate::transpiler::TranspileError>,
}

pub fn transpile_simd(program: &Program, stem: &str, version: &str) -> SimdOutput {
    let kernel_names = program
        .items
        .iter()
        .filter_map(|i| match i {
            Item::Kernel(k) => Some(k.name.clone()),
            _ => None,
        })
        .collect::<Vec<_>>();
    let kernels = program
        .items
        .iter()
        .filter_map(|i| match i {
            Item::Kernel(k) => Some(k.clone()),
            _ => None,
        })
        .collect::<Vec<_>>();
    let renamed = crate::transpiler::rename_top_level_main(program, "boring_main");
    let config = crate::transpiler::TranspileConfig {
        gpu_kernels: kernels.clone(),
        is_gpu_target: true,
        is_simd_target: true,
        ..Default::default()
    };
    let general = crate::transpiler::transpile_with_config(&renamed, config);
    let (has_main, main_throws) = crate::transpiler::detect_boring_main(&renamed, &general);

    let mut initial_errors = general.errors;
    for item in &program.items {
        if let Item::Fn(function) = item {
            if function
                .return_ty
                .as_ref()
                .is_some_and(|ty| ty.gpu_resident_qual().is_some())
            {
                initial_errors.push(crate::errors::SourceError::at(
                    format!("function '{}': GPU-resident returns are not yet supported by --target simd; materialize and return a plain array", function.name),
                    function.line, function.col,
                ));
            }
        }
    }
    for k in &kernels {
        for field in &k.fields {
            if matches!(
                field.qual,
                GpuQual::Actor
                    | GpuQual::ActorGlobal
                    | GpuQual::ActorUnified
                    | GpuQual::Local
                    | GpuQual::Surface
            ) {
                initial_errors.push(crate::errors::SourceError::at(
                    format!("kernel '{}': field '{}' uses {:?} storage, which is not yet supported by --target simd", k.name, field.name, field.qual),
                    field.line, field.col,
                ));
            }
        }
        if k.methods
            .iter()
            .any(|m| crate::interpreter::eval_gpu::stmts_use_gpu_warp(&m.body))
        {
            initial_errors.push(crate::errors::SourceError::at(
                format!("kernel '{}': `.warp` collectives are not yet supported by --target simd; use block-level scalar code", k.name),
                k.line, k.col,
            ));
        }
    }
    let mut e = Emitter {
        out: String::new(),
        errors: initial_errors,
        fields: std::collections::HashSet::new(),
        field_axes: std::collections::HashMap::new(),
    };
    e.raw(PRELUDE);
    for kernel in &kernels {
        e.kernel(kernel);
    }
    e.raw(&general.code);
    if has_main {
        if main_throws {
            e.raw("\nfn main() { if let Err(e) = boring_main() { eprintln!(\"error: {}\", e); std::process::exit(1); } }\n");
        } else {
            e.raw("\nfn main() { boring_main(); }\n");
        }
    } else {
        e.raw("\nfn main() {}\n");
    }
    let cargo_toml = format!("[package]\nname = \"{}-simd\"\nversion = \"{}\"\nedition = \"2021\"\n\n[profile.release]\nopt-level = 3\nlto = \"thin\"\ncodegen-units = 1\n\n", stem.replace('_', "-"), version);
    SimdOutput {
        host_rs: e.out,
        cargo_toml,
        kernel_names,
        errors: e.errors,
    }
}

const PRELUDE: &str = r#"// Generated by `boring build --target simd`.
// CPU execution preserves Boring's 3-D grid/block coordinates.  The x axis is
// chunked at the detected native vector width; the final partial chunk is scalar.
#[derive(Clone, Copy, Debug)] struct __BoringCpu;
fn __boring_gpu_device() -> __BoringCpu { __BoringCpu }
fn __boring_gpu_queue() -> __BoringCpu { __BoringCpu }
fn set_gpu_batch_limit(_: i64) {}
fn __boring_gpu_name(_: usize) -> String { format!("CPU SIMD ({})", __boring_simd_name()) }
fn __boring_gpu_total_mem(_: usize) -> i64 { 0 }
fn __boring_gpu_used_mem(_: usize) -> i64 { 0 }
fn __boring_gpu_free_mem(_: usize) -> i64 { 0 }
fn __boring_gpu_utilization(_: usize) -> f64 { 0.0 }
fn __boring_gpu_temperature(_: usize) -> f64 { 0.0 }
fn __boring_gpu_power_usage(_: usize) -> f64 { 0.0 }
fn __boring_gpu_power_limit(_: usize) -> f64 { 0.0 }
fn __boring_gpu_memory_bandwidth(_: usize) -> f64 { 0.0 }
fn __boring_gpu_compute_capability(_: usize) -> String { __boring_simd_name().into() }

#[derive(Clone, Copy, Debug)] struct __BoringDim3 { x: i32, y: i32, z: i32 }
fn __boring_simd_lanes() -> usize {
    if std::env::var_os("BORING_SIMD_SCALAR").is_some() { return 1; }
    #[cfg(any(target_arch="x86", target_arch="x86_64"))] {
        if std::is_x86_feature_detected!("avx512f") { return 16; }
        if std::is_x86_feature_detected!("avx2") { return 8; }
        if std::is_x86_feature_detected!("sse2") { return 4; }
    }
    #[cfg(target_arch="aarch64")] { if std::arch::is_aarch64_feature_detected!("neon") { return 4; } }
    1
}
fn __boring_simd_name() -> &'static str {
    match __boring_simd_lanes() { 16 => "AVX-512", 8 => "AVX2", 4 => { #[cfg(target_arch="aarch64")] { return "NEON"; } #[cfg(not(target_arch="aarch64"))] { "SSE2" } }, _ => "scalar" }
}
#[allow(dead_code)] #[derive(Clone, Debug, PartialEq)] enum BoringGpuArg<T> { Host(Vec<T>) }
impl<T> BoringGpuArg<T> { fn len(&self) -> usize { match self { Self::Host(v) => v.len() } } }
"#;

struct Emitter {
    out: String,
    errors: Vec<crate::transpiler::TranspileError>,
    fields: std::collections::HashSet<String>,
    field_axes: std::collections::HashMap<String, Vec<LabeledAxis>>,
}
impl Emitter {
    fn raw(&mut self, s: &str) {
        self.out.push_str(s);
    }
    fn line(&mut self, n: usize, s: &str) {
        self.out.push_str(&"    ".repeat(n));
        self.out.push_str(s);
        self.out.push('\n');
    }
    fn kernel(&mut self, k: &KernelDecl) {
        self.fields = k.fields.iter().map(|f| f.name.clone()).collect();
        self.field_axes = k
            .fields
            .iter()
            .filter_map(|f| {
                f.ty.as_labeled_array()
                    .map(|(_, axes)| (f.name.clone(), axes.to_vec()))
            })
            .collect();
        self.line(0, &format!("#[derive(Debug)] struct {} {{", k.name));
        for f in &k.fields {
            self.line(1, &format!("{}: {},", f.name, ty(&f.ty)));
        }
        self.line(0, "}");
        self.line(0, &format!("impl {} {{", k.name));
        self.line(1, "fn new(_: __BoringCpu, _: __BoringCpu) -> Self {");
        self.line(2, "Self {");
        for f in &k.fields {
            self.line(3, &format!("{}: {},", f.name, default_value(&f.ty)));
        }
        self.line(2, "}");
        self.line(1, "}");
        for f in &k.fields {
            if is_array(&f.ty) {
                let t = elem_ty(&f.ty);
                self.line(
                    1,
                    &format!(
                        "fn copy_{}_to_host(&self) -> Vec<{}> {{ self.{}.clone() }}",
                        f.name, t, f.name
                    ),
                );
                self.line(
                    1,
                    &format!(
                        "fn copy_{}_to_device(&mut self, v: &[{}]) {{ self.{} = v.to_vec(); }}",
                        f.name, t, f.name
                    ),
                );
                self.line(1, &format!("fn resize_{}(&mut self, n: usize) {{ self.{}.resize(n, Default::default()); }}", f.name, f.name));
            }
        }
        self.line(1, "#[inline(never)] fn dispatch(&mut self, gx: u32, gy: u32, gz: u32, dx: u32, dy: u32, dz: u32) -> Result<(), Box<dyn std::error::Error + Send + Sync>> {");
        self.line(
            2,
            "#[cfg(any(target_arch=\"x86\", target_arch=\"x86_64\"))] unsafe {",
        );
        self.line(3, "if std::env::var_os(\"BORING_SIMD_SCALAR\").is_none() {");
        self.line(4, "if std::is_x86_feature_detected!(\"avx512f\") { return self.dispatch_avx512(gx,gy,gz,dx,dy,dz); }");
        self.line(4, "if std::is_x86_feature_detected!(\"avx2\") { return self.dispatch_avx2(gx,gy,gz,dx,dy,dz); }");
        self.line(4, "if std::is_x86_feature_detected!(\"sse2\") { return self.dispatch_sse2(gx,gy,gz,dx,dy,dz); }");
        self.line(3, "}");
        self.line(2, "}");
        self.line(2, "#[cfg(target_arch=\"aarch64\")] { if std::env::var_os(\"BORING_SIMD_SCALAR\").is_none() && std::arch::is_aarch64_feature_detected!(\"neon\") { return self.dispatch_impl(gx,gy,gz,dx,dy,dz,4); } }");
        self.line(2, "self.dispatch_impl(gx,gy,gz,dx,dy,dz,1)");
        self.line(1, "}");
        self.line(1, "#[cfg(any(target_arch=\"x86\", target_arch=\"x86_64\"))] #[target_feature(enable=\"avx512f\")] unsafe fn dispatch_avx512(&mut self,gx:u32,gy:u32,gz:u32,dx:u32,dy:u32,dz:u32)->Result<(),Box<dyn std::error::Error+Send+Sync>> { self.dispatch_impl(gx,gy,gz,dx,dy,dz,16) }");
        self.line(1, "#[cfg(any(target_arch=\"x86\", target_arch=\"x86_64\"))] #[target_feature(enable=\"avx2\")] unsafe fn dispatch_avx2(&mut self,gx:u32,gy:u32,gz:u32,dx:u32,dy:u32,dz:u32)->Result<(),Box<dyn std::error::Error+Send+Sync>> { self.dispatch_impl(gx,gy,gz,dx,dy,dz,8) }");
        self.line(1, "#[cfg(any(target_arch=\"x86\", target_arch=\"x86_64\"))] #[target_feature(enable=\"sse2\")] unsafe fn dispatch_sse2(&mut self,gx:u32,gy:u32,gz:u32,dx:u32,dy:u32,dz:u32)->Result<(),Box<dyn std::error::Error+Send+Sync>> { self.dispatch_impl(gx,gy,gz,dx,dy,dz,4) }");
        self.line(1, "#[inline(always)] fn dispatch_impl(&mut self, gx: u32, gy: u32, gz: u32, dx: u32, dy: u32, dz: u32, __lanes: usize) -> Result<(), Box<dyn std::error::Error + Send + Sync>> {");
        self.line(
            2,
            "let __block_dim = __BoringDim3 { x: dx as i32, y: dy as i32, z: dz as i32 };",
        );
        self.line(
            2,
            "let __grid_dim = __BoringDim3 { x: gx as i32, y: gy as i32, z: gz as i32 };",
        );
        self.line(2, "for bz in 0..gz as usize { for by in 0..gy as usize { for bx in 0..gx as usize { for tz in 0..dz as usize { for ty in 0..dy as usize { let mut tx=0usize; while tx<dx as usize {");
        self.line(3, "let __end = (tx + __lanes).min(dx as usize);");
        self.line(3, "for __x in tx..__end {");
        self.line(
            4,
            "let __thread = __BoringDim3 { x: __x as i32, y: ty as i32, z: tz as i32 };",
        );
        self.line(
            4,
            "let __block = __BoringDim3 { x: bx as i32, y: by as i32, z: bz as i32 };",
        );
        if let Some(m) = k.methods.first() {
            for s in &m.body {
                self.stmt(s, 4);
            }
        }
        self.line(3, "} tx = __end;");
        self.line(2, "} } } } } }");
        self.line(2, "Ok(())");
        self.line(1, "}");
        self.line(0, "}");
    }
    fn stmt(&mut self, s: &Stmt, n: usize) {
        match s {
            Stmt::Let(v) => {
                let value = v
                    .value
                    .as_ref()
                    .map(|x| self.expr(x))
                    .unwrap_or_else(|| "Default::default()".into());
                let value = match &v.ty {
                    Some(t) if !is_array(t) => format!("({value}) as {}", ty(t)),
                    _ => value,
                };
                self.line(
                    n,
                    &format!(
                        "let {}{}{} = {};",
                        if v.binding.is_mutable() { "mut " } else { "" },
                        v.name,
                        v.ty.as_ref()
                            .map(|t| format!(": {}", ty(t)))
                            .unwrap_or_default(),
                        value
                    ),
                );
            }
            Stmt::Expr(x) => {
                let x = self.expr(x);
                self.line(n, &format!("{};", x));
            }
            Stmt::If(i) => {
                for (j, (condition, body)) in i.branches.iter().enumerate() {
                    let condition = self.expr(condition);
                    self.line(
                        n,
                        &format!("{}if {} {{", if j == 0 { "" } else { "else " }, condition),
                    );
                    for s in body {
                        self.stmt(s, n + 1);
                    }
                    self.line(n, "}");
                }
                if let Some(body) = &i.else_body {
                    self.line(n, "else {");
                    for s in body {
                        self.stmt(s, n + 1);
                    }
                    self.line(n, "}");
                }
            }
            Stmt::For(f) => {
                let iterable = self.expr(&f.iterable);
                self.line(n, &format!("for {} in {} {{", f.vars.join(", "), iterable));
                for s in &f.body {
                    self.stmt(s, n + 1);
                }
                self.line(n, "}");
            }
            Stmt::Comment(c) if c == "sync" => {
                self.errors.push(crate::errors::SourceError::at_line(
                    "`sync` is not yet supported inside a --target simd kernel",
                    0,
                ));
                self.line(n, "/* rejected unsupported block barrier */");
            }
            Stmt::Comment(c) => self.line(n, &format!("//{}", c)),
            Stmt::While(w) => {
                let condition = self.expr(&w.condition);
                self.line(n, &format!("while {} {{", condition));
                for s in &w.body {
                    self.stmt(s, n + 1);
                }
                self.line(n, "}");
            }
            Stmt::Loop(l) => {
                self.line(n, "loop {");
                for s in &l.body {
                    self.stmt(s, n + 1);
                }
                self.line(n, "}");
            }
            Stmt::Break(_, _) => self.line(n, "break;"),
            Stmt::Continue(_) => self.line(n, "continue;"),
            other => {
                let (line, col) = stmt_position(other);
                self.errors.push(crate::errors::SourceError::at(
                    "this statement is not yet supported inside a --target simd kernel",
                    line,
                    col,
                ));
                self.line(n, "/* rejected unsupported SIMD kernel statement */");
            }
        }
    }
    fn expr(&mut self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::Int(v) => v.to_string(),
            ExprKind::UInt64(v) => format!("{v}u64"),
            ExprKind::Float(v) => format!("{v}"),
            ExprKind::Bool(v) => v.to_string(),
            ExprKind::Var(v) => {
                if matches!(v.as_str(), "thread" | "block" | "block_dim") {
                    format!("__{v}")
                } else if v == "warp" {
                    "__warp".into()
                } else if self.fields.contains(v) {
                    format!("self.{v}")
                } else {
                    v.clone()
                }
            }
            ExprKind::DotIdent(v) if matches!(v.as_str(), "thread" | "block" | "block_dim") => {
                format!("__{v}")
            }
            ExprKind::Field(a, b) => {
                if let ExprKind::Var(field) = &a.kind {
                    if let Some(axes) = self.field_axes.get(field) {
                        if let Some(axis) = axes.iter().find(|axis| axis.label == *b) {
                            if let Some(size) = &axis.size {
                                return crate::transpiler::helpers::const_expr_to_c_like(&size.0);
                            }
                        }
                    }
                }
                if let ExprKind::Field(root, base) = &a.kind {
                    if matches!(&root.kind,ExprKind::Var(v) if v=="gpu") {
                        let builtin = match base.as_str() {
                            "thread" => Some("__thread"),
                            "block" => Some("__block"),
                            "block_dim" | "blockDim" => Some("__block_dim"),
                            "grid_dim" | "gridDim" => Some("__grid_dim"),
                            _ => None,
                        };
                        if let Some(builtin) = builtin {
                            format!("{builtin}.{b}")
                        } else {
                            format!("{}.{}", self.expr(a), b)
                        }
                    } else {
                        format!("{}.{}", self.expr(a), b)
                    }
                } else {
                    format!("{}.{}", self.expr(a), b)
                }
            }
            ExprKind::Index(a, b) => format!("{}[({}) as usize]", self.expr(a), self.expr(b)),
            ExprKind::LabeledIndex(a, args) => self.labeled_index(a, args),
            ExprKind::Assign(a, b) => format!("{} = {}", self.lvalue(a), self.expr(b)),
            ExprKind::BinOp(op, a, b) => {
                let left = self.expr(a);
                let right = self.expr(b);
                match binop(op) {
                    Some(op) => format!("({left} {op} {right})"),
                    None => {
                        self.errors.push(crate::errors::SourceError::at(
                            "identity/type-test operators are not supported inside a --target simd kernel",
                            e.line,
                            e.col,
                        ));
                        "/* rejected SIMD identity test */ false".into()
                    }
                }
            }
            ExprKind::UnaryOp(op, a) => format!(
                "({}{})",
                match op {
                    UnaryOp::Neg => "-",
                    UnaryOp::Not | UnaryOp::BitNot => "!",
                },
                self.expr(a)
            ),
            ExprKind::Cast(a, t) => format!("({} as {})", self.expr(a), ty(t)),
            ExprKind::Range {
                start,
                end,
                inclusive,
            } => format!(
                "{}..{}{}",
                self.expr(start),
                if *inclusive { "=" } else { "" },
                self.expr(end)
            ),
            ExprKind::Call(c, args) => format!(
                "{}({})",
                self.expr(c),
                args.iter()
                    .map(|a| self.expr(&a.value))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            ExprKind::MethodCall(o, m, args) => format!(
                "{}.{}({})",
                self.expr(o),
                m,
                args.iter()
                    .map(|a| self.expr(&a.value))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            ExprKind::If(i) => {
                let mut out = String::new();
                for (index, (condition, body)) in i.branches.iter().enumerate() {
                    if index > 0 {
                        out.push_str(" else ");
                    }
                    out.push_str(&format!(
                        "if {} {{ {} }}",
                        self.expr(condition),
                        self.expr_body(body)
                    ));
                }
                if let Some(body) = &i.else_body {
                    out.push_str(&format!(" else {{ {} }}", self.expr_body(body)));
                } else {
                    out.push_str(" else { Default::default() }");
                }
                out
            }
            _ => {
                self.errors.push(crate::errors::SourceError::at(
                    "this expression is not yet supported inside a --target simd kernel",
                    e.line,
                    e.col,
                ));
                "/* rejected unsupported SIMD expression */ 0".into()
            }
        }
    }
    fn expr_body(&mut self, body: &[Stmt]) -> String {
        let mut parts = Vec::new();
        for stmt in body {
            match stmt {
                Stmt::Expr(e) => parts.push(self.expr(e)),
                Stmt::Let(v) => {
                    let value = v
                        .value
                        .as_ref()
                        .map(|e| self.expr(e))
                        .unwrap_or_else(|| "Default::default()".into());
                    let value = match &v.ty {
                        Some(t) if !is_array(t) => format!("({value}) as {}", ty(t)),
                        _ => value,
                    };
                    parts.push(format!(
                        "let {}{}{} = {}",
                        if v.binding.is_mutable() { "mut " } else { "" },
                        v.name,
                        v.ty.as_ref()
                            .map(|t| format!(": {}", ty(t)))
                            .unwrap_or_default(),
                        value
                    ));
                }
                other => {
                    let (line, col) = stmt_position(other);
                    self.errors.push(crate::errors::SourceError::at(
                        "this statement is not supported in a SIMD kernel expression block",
                        line,
                        col,
                    ));
                    parts.push("Default::default()".into());
                }
            }
        }
        parts.join("; ")
    }
    fn lvalue(&mut self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::Var(v) => {
                if v.starts_with("__") {
                    v.clone()
                } else if self.fields.contains(v) {
                    format!("self.{v}")
                } else {
                    v.clone()
                }
            }
            ExprKind::Index(a, b) => format!("{}[({}) as usize]", self.lvalue(a), self.expr(b)),
            ExprKind::LabeledIndex(a, args) => self.labeled_index(a, args),
            ExprKind::Field(a, b) => format!("{}.{}", self.lvalue(a), b),
            _ => self.expr(e),
        }
    }
    fn labeled_index(&mut self, object: &Expr, args: &[Arg]) -> String {
        let ExprKind::Var(field) = &object.kind else {
            self.errors.push(crate::errors::SourceError::at(
                "SIMD labeled indexing currently requires a direct kernel field",
                object.line,
                object.col,
            ));
            return "/* rejected labeled index */ 0".into();
        };
        let Some(axes) = self.field_axes.get(field).cloned() else {
            self.errors.push(crate::errors::SourceError::at(
                format!("kernel field '{}' has no labeled dimensions", field),
                object.line,
                object.col,
            ));
            return "/* rejected labeled index */ 0".into();
        };
        let mut terms = Vec::new();
        let mut stride = "1".to_string();
        for axis in &axes {
            let Some(arg) = args
                .iter()
                .find(|arg| arg.label.as_deref() == Some(axis.label.as_str()))
            else {
                self.errors.push(crate::errors::SourceError::at(
                    format!("missing '{}' axis in labeled index", axis.label),
                    object.line,
                    object.col,
                ));
                continue;
            };
            terms.push(format!(
                "(({}) as usize * ({}))",
                self.expr(&arg.value),
                stride
            ));
            if let Some(size) = &axis.size {
                stride = format!(
                    "({stride}) * (({}) as usize)",
                    crate::transpiler::helpers::const_expr_to_c_like(&size.0)
                );
            }
        }
        format!("self.{field}[{}]", terms.join(" + "))
    }
}

fn stmt_position(stmt: &Stmt) -> (usize, usize) {
    match stmt {
        Stmt::Let(s) => (s.line, s.col),
        Stmt::LetDestructure(s) => (s.line, s.col),
        Stmt::Return(s) => (s.line, s.col),
        Stmt::Throw(s) => (s.line, s.col),
        Stmt::If(s) => (s.line, s.col),
        Stmt::IfLet(s) => (s.line, s.col),
        Stmt::Match(s) => (s.line, s.col),
        Stmt::While(s) => (s.line, s.col),
        Stmt::WhileLet(s) => (s.line, s.col),
        Stmt::DoWhile(s) => (s.line, s.col),
        Stmt::Loop(s) => (s.line, s.col),
        Stmt::For(s) => (s.line, s.col),
        Stmt::Guard(s) => (s.line, s.col),
        Stmt::Try(s) => (s.line, s.col),
        Stmt::Expr(e) | Stmt::Wait(e, _) | Stmt::Yield(e, _) => (e.line, e.col),
        Stmt::Fn(s) => (s.line, s.col),
        Stmt::Struct(s) => (s.line, s.col),
        Stmt::Enum(s) => (s.line, s.col),
        Stmt::Mod(s) => (s.line, s.col),
        Stmt::Alias(s) => (s.line, s.col),
        Stmt::KernelBlock(s) => (s.line, s.col),
        Stmt::With(s) => (s.line, s.col),
        Stmt::Break(line, _) | Stmt::Continue(line) => (*line, 0),
        Stmt::Defer(_) | Stmt::Comment(_) => (0, 0),
    }
}
fn base(t: &Type) -> &Type {
    match t {
        Type::Mut(x) | Type::Qualified(x, _) => base(x),
        _ => t,
    }
}
fn is_array(t: &Type) -> bool {
    matches!(
        base(t),
        Type::Array(_) | Type::ArrayN(_, _) | Type::LabeledArray(_, _)
    )
}
fn elem_ty(t: &Type) -> String {
    match base(t) {
        Type::Array(x) | Type::ArrayN(x, _) => ty(x),
        Type::LabeledArray(x, _) => ty(x),
        _ => "f64".into(),
    }
}
fn ty(t: &Type) -> String {
    match base(t) {
        Type::Int => "i32".into(),
        Type::Uint => "u32".into(),
        Type::Float64 => "f64".into(),
        Type::Float32 => "f32".into(),
        Type::Bool => "bool".into(),
        Type::Named(n) => match n.as_str() {
            "float32" => "f32".into(),
            "float" | "float64" => "f64".into(),
            "int" => "i32".into(),
            "uint" => "u32".into(),
            "int8" => "i8".into(),
            "int16" => "i16".into(),
            "int32" => "i32".into(),
            "int64" => "i64".into(),
            "uint8" => "u8".into(),
            "uint16" => "u16".into(),
            "uint32" => "u32".into(),
            "uint64" => "u64".into(),
            "bool" => "bool".into(),
            _ => "isize".into(),
        },
        Type::Array(_) | Type::ArrayN(_, _) | Type::LabeledArray(_, _) => {
            format!("Vec<{}>", elem_ty(t))
        }
        _ => "isize".into(),
    }
}
fn default_value(t: &Type) -> String {
    if is_array(t) {
        let len = match base(t) {
            Type::ArrayN(_, n) => Some(*n),
            other => other
                .labeled_array_len()
                .and_then(|n| usize::try_from(n).ok()),
        };
        match len {
            Some(n) => format!("vec![Default::default(); {n}]"),
            None => "Vec::new()".into(),
        }
    } else {
        "Default::default()".into()
    }
}
fn binop(op: &BinOp) -> Option<&'static str> {
    match op {
        BinOp::Add => Some("+"),
        BinOp::Sub => Some("-"),
        BinOp::Mul => Some("*"),
        BinOp::Div => Some("/"),
        BinOp::Rem => Some("%"),
        BinOp::Eq | BinOp::RefEq => Some("=="),
        BinOp::NotEq => Some("!="),
        BinOp::Lt => Some("<"),
        BinOp::LtEq => Some("<="),
        BinOp::Gt => Some(">"),
        BinOp::GtEq => Some(">="),
        BinOp::And => Some("&&"),
        BinOp::Or => Some("||"),
        BinOp::BitAnd => Some("&"),
        BinOp::BitOr => Some("|"),
        BinOp::BitXor => Some("^"),
        BinOp::Shl => Some("<<"),
        BinOp::Shr => Some(">>"),
        BinOp::Is | BinOp::IsNot => None,
    }
}
